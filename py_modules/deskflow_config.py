"""Generation of Deskflow's ``Deskflow.conf``.

``deskflow-core`` accepts no host, port, or name arguments -- the INI file is the only
channel. That also keeps configuration out of argv, which is world-readable through
``/proc/<pid>/cmdline``.
"""

import os
import tempfile

__all__ = ["ConfigError", "render_ini", "write_config"]

CORE_MODE_CLIENT = 1
CORE_MODE_SERVER = 2

_FORBIDDEN = ("\n", "\r", "\x00", "\x1b")


class ConfigError(Exception):
    pass


def _safe(field, value):
    """Refuse, never escape.

    Validation should already have rejected anything with a line break. Reaching this
    function with one means an upstream control failed, and quietly escaping it would
    hide that. Refusing turns a silent config-injection into a visible error.
    """
    text = str(value)
    for bad in _FORBIDDEN:
        if bad in text:
            raise ConfigError("{0} contains an illegal character".format(field))
    return text


def _bool(value):
    return "true" if value else "false"


def render_ini(settings, cert_path):
    """Render the INI text for these settings. Pure -- does no I/O."""
    mode = settings["mode"]
    core_mode = CORE_MODE_CLIENT if mode == "client" else CORE_MODE_SERVER

    name = _safe("client_name", settings["client_name"])
    port = _safe("server_port", int(settings["server_port"]))
    certificate = _safe("certificate", cert_path)

    lines = [
        "; Generated by deskflow-decky. Manual edits are overwritten on every start.",
        "",
        "[core]",
        "coreMode={0}".format(core_mode),
        "port={0}".format(port),
        "computerName={0}".format(name),
        "",
    ]

    if core_mode == CORE_MODE_CLIENT:
        lines += [
            "[client]",
            "remoteHost={0}".format(_safe("server_host", settings["server_host"])),
            "languageSync=false",
            "",
        ]

    log_level_map = {"error": 1, "warn": 2, "info": 4, "debug": 6}
    log_int = log_level_map.get(settings.get("log_level", "info"), 4)

    lines += [
        "[security]",
        "tlsEnabled={0}".format(_bool(settings["tls_enabled"])),
        "checkPeerFingerprints={0}".format(_bool(settings["check_peer_fingerprints"])),
        "certificate={0}".format(certificate),
        "keySize=2048",
        "",
        "[daemon]",
        "logLevel={0}".format(log_int),
        "",
    ]

    return "\n".join(lines)


def write_config(path, settings, cert_path):
    """Write the INI atomically with owner-only permissions. Returns the path."""
    text = render_ini(settings, cert_path)

    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, mode=0o700, exist_ok=True)

    # Write to a temporary file in the same directory and rename, so a crash midway
    # never leaves the helper reading a half-written config.
    handle, temp_path = tempfile.mkstemp(dir=directory, prefix=".Deskflow.conf.")
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as stream:
            stream.write(text)
        os.chmod(temp_path, 0o600)
        os.replace(temp_path, path)
    except BaseException:
        if os.path.exists(temp_path):
            os.unlink(temp_path)
        raise

    return path
